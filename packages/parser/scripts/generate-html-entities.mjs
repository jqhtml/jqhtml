#!/usr/bin/env node
/**
 * Regenerates src/html_entity_table.ts from the WHATWG named character reference
 * table:
 *
 *   curl -o entities.json https://html.spec.whatwg.org/entities.json
 *   node scripts/generate-html-entities.mjs entities.json
 *
 * Keys are kept as the spec lists them, without the leading '&': the 2125 names that
 * need their ';' and the 106 legacy names that also match without it.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const source = process.argv[2];
if (!source) {
  console.error('Usage: node scripts/generate-html-entities.mjs <entities.json>');
  process.exit(1);
}

const table = JSON.parse(fs.readFileSync(source, 'utf8'));
const ascii = (s) => s.replace(/[^\x20-\x7e]|["\\]/g, (c) => '\\u' + c.charCodeAt(0).toString(16).padStart(4, '0'));
const entries = Object.keys(table)
  .sort()
  .map((key) => `  "${key.slice(1)}": "${ascii(table[key].characters)}",`);

const out = `// Generated by scripts/generate-html-entities.mjs from
// https://html.spec.whatwg.org/entities.json - do not edit.
// Named character references, without the leading '&' (${entries.length} entries).

export const HTML_NAMED_REFERENCES: Record<string, string> = {
${entries.join('\n')}
};
`;
const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'html_entity_table.ts');
fs.writeFileSync(target, out);
console.log(`Wrote ${entries.length} entries to ${target}`);
